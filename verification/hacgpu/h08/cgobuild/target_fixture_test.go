func TestGeneratedTestmainHermeticBytesAndSelection(t *testing.T) {
	p := targetFixture(t)
	if p.CPU13.MainSource != fixtureTestmain || p.CPU13.MainSHA256 != digest([]byte(fixtureTestmain)) {
		t.Fatalf("source-derived fixture bytes differ:\n%s", p.CPU13.MainSource)
	}
	if !slices.Equal(p.CPU13.TestCopies, []string{Module + "/internal/adapter", TensorPackage}) {
		t.Fatalf("test copies differ: %q", p.CPU13.TestCopies)
	}
	mainBoundaryControls(t, p, []byte(fixtureTestmain))
	cache := filepath.Join(p.Options.WorkRoot, "cache", "testmain-d")
	if e := os.MkdirAll(filepath.Dir(cache), 0700); e != nil {
		t.Fatal(e)
	}
	if e := os.WriteFile(cache, []byte(fixtureTestmain), 0600); e != nil {
		t.Fatal(e)
	}
	var rows []map[string]any
	for _, pkg := range p.Packages {
		rows = append(rows, map[string]any{"ImportPath": pkg.ImportPath, "Dir": pkg.Directory, "GoFiles": pkg.Go, "EmbedFiles": pkg.Embed})
		if slices.Contains(p.CPU13.TestCopies, pkg.ImportPath) {
			files := slices.Clone(pkg.Go)
			if pkg.ImportPath == TensorPackage {
				files = append(files, pkg.TestGo...)
			}
			rows = append(rows, map[string]any{"ImportPath": pkg.ImportPath + testSuffix, "Dir": pkg.Directory, "ForTest": TensorPackage, "GoFiles": files, "EmbedFiles": pkg.Embed})
		}
	}
	rows = append(rows,
		map[string]any{"ImportPath": TensorPackage + "_test" + testSuffix, "Dir": filepath.Join(p.Options.Root, "internal/tensor"), "ForTest": TensorPackage, "Name": "tensor_test", "GoFiles": []string{"adapter_test.go", OverlayName}, "Imports": []string{Module + "/internal/adapter" + testSuffix, "os", "testing", Module + "/verification/hacgpu/h08"}},
		map[string]any{"ImportPath": TensorPackage + ".test", "Dir": filepath.Join(p.Options.Root, "internal/tensor"), "Name": "main", "GoFiles": []string{cache}},
	)
	var out strings.Builder
	for _, row := range rows {
		if e := json.NewEncoder(&out).Encode(row); e != nil {
			t.Fatal(e)
		}
	}
	stdout := []byte(out.String())
	if e := verifyActualSelection(p, stdout); e != nil {
		t.Fatalf("hermetic selection differs: %v", e)
	}
	selectionBoundaryControls(t, p, stdout)
	for _, mutation := range []string{fixtureTestmain + "\n", strings.Replace(fixtureTestmain, "TestAlpha", "TestOther", 1)} {
		if e := os.WriteFile(cache, []byte(mutation), 0600); e != nil {
			t.Fatal(e)
		}
		if e := verifyActualSelection(p, stdout); e == nil {
			t.Fatal("changed generated bytes reached selection boundary")
		}
		file := filepath.Join(p.Options.WorkRoot, "_testmain.go")
		if e := validateMainInputs(p, TensorPackage+".test", []string{file}, map[string]string{file: digest([]byte(mutation))}); e == nil {
			t.Fatal("changed generated bytes reached compiler boundary")
		}
	}
}

func TestQualifiedGoGeneratorAuditRejectsVersionAndLayout(t *testing.T) {
	self, e := os.Executable()
	if e != nil {
		t.Fatal(e)
	}
	for _, control := range []struct{ name, version, message string }{
		{"wrong version", "go1.24.13\n", "requires pinned Go1.27.3"},
		{"missing layout", "go1.27.3\n", "qualified Go1.27.3 generator layout differs: bin/go"},
	} {
		t.Run(control.name, func(t *testing.T) {
			root := t.TempDir()
			if e := os.WriteFile(filepath.Join(root, "VERSION"), []byte(control.version), 0600); e != nil {
				t.Fatal(e)
			}
			cmd := exec.Command(self, "-test.v", "-test.run=^TestQualifiedGo1273GeneratedTestmainMatchesRealGo0Generator$")
			cmd.Env = append(os.Environ(), "GOROOT="+root, "NANOPORE_QUALIFIED_HOST_TESTS=1")
			output, e := cmd.CombinedOutput()
			t.Logf("qualification rejection argv=%q GOROOT=%s NANOPORE_QUALIFIED_HOST_TESTS=1 output:\n%s", cmd.Args, root, output)
			failure, ok := e.(*exec.ExitError)
			if !ok || failure.ExitCode() != 1 || !strings.Contains(string(output), control.message) || strings.Contains(string(output), "--- SKIP:") || strings.Contains(string(output), "CGO0 fake-module generator argv=") {
				t.Fatalf("explicit qualification did not fail before generator launch: %v", e)
			}
		})
	}
}
